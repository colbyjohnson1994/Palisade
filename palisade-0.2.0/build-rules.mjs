/**
 * Writes rules/*.json, cosmetic-data.js, and youtube.js.
 * The extension loads those files directly. Re-run after editing LISTS
 * or lib/youtube.js:
 *   node build-rules.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LISTS, staticRules } from "./lib/filters.js";

const root = dirname(fileURLToPath(import.meta.url));
const dir = join(root, "rules");
await mkdir(dir, { recursive: true });
const rules = staticRules();
for (const [id, list] of Object.entries(rules)) {
  await writeFile(join(dir, `${id}.json`), `${JSON.stringify(list, null, 2)}\n`);
  console.log(`${id}: ${list.length} rules`);
}
const cosmetic = Object.fromEntries(Object.entries(LISTS).map(([id, list]) => [id, list.cosmetic]));
await writeFile(
  join(root, "cosmetic-data.js"),
  `/* Generated by build-rules.mjs. Do not edit by hand. */\nself.PALISADE_COSMETIC = ${JSON.stringify(cosmetic)};\n`,
);

const core = await readFile(join(root, "lib/youtube.js"), "utf8");
const boot = await readFile(join(root, "youtube-boot.js"), "utf8");
const body = core.replace(/^export /gm, "").replace(/^\/\*\*[\s\S]*?\*\/\n/, "");
const page = `/* Generated by build-rules.mjs from lib/youtube.js and youtube-boot.js. Do not edit by hand. */\n(() => {\n${body}\n${boot}\n})();\n`;
await writeFile(join(root, "youtube.js"), page);
console.log("youtube.js");
